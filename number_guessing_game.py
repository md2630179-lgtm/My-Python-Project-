# ==============================================================
# প্রজেক্ট: সংখ্যা অনুমান করার খেলা (Number Guessing Game)
# ==============================================================
# খেলার নিয়ম: কম্পিউটার ১ থেকে ১০০ এর মধ্যে একটা সংখ্যা মনে মনে ঠিক করবে।
# তুমি সেটা অনুমান করবে। প্রতিবার কম্পিউটার বলবে তোমার অনুমান
# বেশি হয়েছে, কম হয়েছে, নাকি ঠিক হয়েছে।
#
# এই প্রজেক্টে যা শিখবে:
#   ১) import        ২) function        ৩) while লুপ
#   ৪) if/elif/else  ৫) try/except      ৬) f-string
# ==============================================================

# random নামের মডিউলটা আমরা আমদানি (import) করছি।
# কেন? কারণ কম্পিউটারকে একটা এলোমেলো (random) সংখ্যা বানাতে হবে,
# আর সেই কাজের টুলগুলো এই মডিউলের ভেতরে আগে থেকেই বানানো আছে।
import random


# def দিয়ে একটা ফাংশন (function) বানাচ্ছি, নাম play_one_round।
# কেন? এক রাউন্ড খেলার পুরো কাজটা একটা "প্যাকেজে" রাখছি,
# যাতে নিচে বারবার এটাকে ডাকলেই আবার নতুন রাউন্ড শুরু হয়।
# কোড বারবার লিখতে হয় না।
def play_one_round():

    # random.randint(1, 100) মানে ১ থেকে ১০০ এর মধ্যে যেকোনো একটা পূর্ণ সংখ্যা।
    # এটাই কম্পিউটারের "লুকানো সংখ্যা", তাই secret_number নামের বাক্সে (variable) রাখছি।
    secret_number = random.randint(1, 100)

    # খেলোয়াড় সর্বোচ্চ কতবার চেষ্টা করতে পারবে, সেটা এখানে ঠিক করছি।
    # আলাদা নাম দিয়ে রাখার সুবিধা: পরে ১০ বার করতে চাইলে শুধু এই এক জায়গায় বদলালেই হবে।
    max_attempts = 7

    # এখন পর্যন্ত কতবার চেষ্টা করা হয়েছে তা গুনতে এই কাউন্টার।
    # শুরুতে ০, কারণ এখনো কেউ কিছু অনুমান করেনি।
    attempts_used = 0

    # print() স্ক্রিনে লেখা দেখায়। \n মানে একটা ফাঁকা লাইন, দেখতে সুন্দর লাগে।
    print("\n🎯 আমি ১ থেকে ১০০ এর মধ্যে একটা সংখ্যা ভেবেছি!")

    # f-string: স্ট্রিংয়ের আগে f লিখলে {} এর ভেতরে ভেরিয়েবলের মান বসানো যায়।
    # এখানে {max_attempts} এর জায়গায় ৭ বসে যাবে।
    print(f"তোমার হাতে {max_attempts} বার সুযোগ আছে।")

    # while লুপ: শর্তটা সত্য থাকা পর্যন্ত নিচের কোড বারবার চলবে।
    # কেন? আমরা জানি না খেলোয়াড় কতবারে ধরবে, তাই "যতক্ষণ সুযোগ বাকি আছে" ধরে ঘুরছি।
    while attempts_used < max_attempts:

        # কয়টা সুযোগ বাকি আছে তা হিসাব করছি (মোট - ব্যবহৃত)।
        chances_left = max_attempts - attempts_used

        # input() ব্যবহারকারীর কাছ থেকে কিছু টাইপ করে নেয়।
        # সে যা লিখবে তা সবসময় টেক্সট (string) হিসেবে guess_text এ জমা হবে,
        # এমনকি সে "45" লিখলেও সেটা সংখ্যা নয়, টেক্সট!
        guess_text = input(f"\n({chances_left} বার বাকি) তোমার অনুমান লেখো: ")

        # try/except: "চেষ্টা করো, ভুল হলে ক্র্যাশ না করে এই বিকল্প পথে যাও।"
        # কেন? ব্যবহারকারী যদি সংখ্যার বদলে "abc" লেখে, int() error দেবে
        # আর প্রোগ্রাম বন্ধ হয়ে যাবে। try/except দিয়ে সেটা সামলাচ্ছি।
        try:
            # int() টেক্সটকে পূর্ণ সংখ্যায় বদলায়, কারণ তুলনা (বড়/ছোট) করতে সংখ্যা লাগে।
            guess = int(guess_text)

        # int() ব্যর্থ হলে Python ValueError নামের ভুল ছোঁড়ে, আমরা সেটাই ধরছি।
        except ValueError:
            print("⚠️ দয়া করে শুধু সংখ্যা লেখো!")

            # continue মানে "এই পাক এখানেই শেষ, লুপের শুরুতে ফিরে যাও।"
            # নিচের কোড না চলায় attempts_used বাড়ছে না, অর্থাৎ ভুল ইনপুটের জন্য সুযোগ নষ্ট হচ্ছে না।
            continue

        # 1 <= guess <= 100 মানে guess ১ থেকে ১০০ এর মধ্যে আছে কিনা।
        # Python এ এভাবে দুই দিকের তুলনা একসাথে লেখা যায়।
        # "not" দিয়ে উল্টে দিচ্ছি: যদি রেঞ্জের বাইরে হয়, তাহলে নিচের কাজ হবে।
        if not 1 <= guess <= 100:
            print("⚠️ সংখ্যাটা ১ থেকে ১০০ এর মধ্যে হতে হবে!")
            continue  # এখানেও সুযোগ নষ্ট না করে আবার জিজ্ঞেস করছি

        # অনুমানটা বৈধ, তাই এবার একটা সুযোগ খরচ হলো। কাউন্টার ১ বাড়াচ্ছি।
        # attempts_used += 1 আর attempts_used = attempts_used + 1 একই জিনিস।
        attempts_used += 1

        # if / elif / else: তিনটা সম্ভাবনার মধ্যে ঠিক একটাই ঘটবে।
        # ১ম সম্ভাবনা: অনুমান লুকানো সংখ্যার চেয়ে ছোট
        if guess < secret_number:
            print("📈 আরও বড় সংখ্যা বলো!")

        # ২য় সম্ভাবনা: (আগেরটা মেলেনি হলে) অনুমান লুকানো সংখ্যার চেয়ে বড়
        elif guess > secret_number:
            print("📉 আরও ছোট সংখ্যা বলো!")

        # বাকি একটাই সম্ভাবনা: বড়ও না, ছোটও না, মানে সমান! জিতে গেছো।
        else:
            print(f"🎉 অভিনন্দন! মাত্র {attempts_used} বারে সংখ্যাটা ধরে ফেলেছো!")

            # return ফাংশন থেকে বেরিয়ে যায় এবং একটা মান ফেরত দেয়।
            # এখানে True ফেরত দিয়ে জানাচ্ছি: "খেলোয়াড় জিতেছে।"
            # ফাংশন শেষ হওয়ায় লুপও আপনাআপনি বন্ধ হয়ে যায়।
            return True

    # এই লাইনে পৌঁছানো মানে লুপ শেষ হয়েছে কিন্তু কেউ ঠিক সংখ্যা ধরতে পারেনি
    # (কারণ ধরতে পারলে আগেই return হয়ে যেত)। তাই সুযোগ শেষ, খেলোয়াড় হেরেছে।
    print(f"\n😢 সুযোগ শেষ! সংখ্যাটা ছিল {secret_number}।")

    # False ফেরত দিয়ে জানাচ্ছি: "খেলোয়াড় হেরেছে।"
    return False


# এই ফাংশনে পুরো খেলা চালানো আর স্কোর গোনার কাজ হবে।
def main():

    # জয় ও হারের হিসাব রাখার জন্য দুটো কাউন্টার, শুরুতে দুটোই ০।
    wins = 0
    losses = 0

    print("=" * 40)  # "=" কে ৪০ বার গুণ করে একটা সাজানো রেখা বানালাম
    print("   🎮 সংখ্যা অনুমান করার খেলায় স্বাগতম!")
    print("=" * 40)

    # while True: এটা "অসীম লুপ", নিজে থেকে কখনো থামে না।
    # কেন? খেলোয়াড় যতবার চাইবে ততবার খেলবে। থামানোর সিদ্ধান্ত
    # নিচে break দিয়ে আমরা নিজেরা নেবো।
    while True:

        # আগের ফাংশনটা ডাকছি। এক রাউন্ড খেলা হবে, তারপর True বা False ফেরত আসবে।
        # সেই ফলাফলটা player_won ভেরিয়েবলে জমা রাখছি।
        player_won = play_one_round()

        # player_won এর মান True হলে জয় ১ বাড়াও, নইলে হার ১ বাড়াও।
        if player_won:
            wins += 1
        else:
            losses += 1

        # এখন পর্যন্ত মোট স্কোর দেখাচ্ছি।
        print(f"\n📊 স্কোর → জয়: {wins} | হার: {losses}")

        # .strip() টেক্সটের আগে-পিছের ফাঁকা জায়গা কেটে দেয়।
        # .lower() সব অক্ষর ছোট হাতের করে দেয় (যাতে "Y" আর "y" একই ধরা হয়)।
        # কেন? ব্যবহারকারী কীভাবে লিখবে তার ঠিক নেই, তাই আগে সবকিছু একরকম করে নিচ্ছি।
        again = input("আবার খেলবে? (y = হ্যাঁ / যেকোনো কিছু = না): ").strip().lower()

        # যদি সে "y" না লেখে, তাহলে অসীম লুপ ভেঙে বেরিয়ে যাও।
        # != মানে "সমান নয়"।
        if again != "y":
            # break লুপটাকে সম্পূর্ণ বন্ধ করে দেয়। এটাই আমাদের প্রোগ্রামের প্রস্থান পথ।
            break

    # লুপ শেষ হলে বিদায় জানাচ্ছি।
    print("\n👋 খেলার জন্য ধন্যবাদ! আবার দেখা হবে।")


# এই শর্তের মানে: "এই ফাইলটা সরাসরি চালালে তবেই main() চালাও।"
# কেন? ধরো ভবিষ্যতে অন্য কোনো ফাইল এটাকে import করলো, তখন যেন খেলাটা
# নিজে নিজে শুরু হয়ে না যায়। এটা পাইথনের একটা খুব প্রচলিত ভালো অভ্যাস।
# __name__ এর মান তখনই "__main__" হয় যখন ফাইলটা সরাসরি চালানো হয়।
if __name__ == "__main__":
    main()
